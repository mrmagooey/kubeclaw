function sleep(ms: number) {
  return new Promise<void>((r) => setTimeout(r, ms));
}

function run(
  cmd: string,
  args: string[],
  opts: { timeout?: number; allowFail?: boolean } = {},
): { ok: boolean; stdout: string; stderr: string } {
  const result = spawnSync(cmd, args, {
    encoding: 'utf8',
    stdio: 'pipe',
    timeout: opts.timeout ?? 60_000,
  });
  if (result.status !== 0 && !opts.allowFail) {
    throw new Error(
      `[${cmd} ${args.join(' ')}] exit ${result.status}\nstderr: ${result.stderr}\nstdout: ${result.stdout}`,
    );
  }
  return {
    ok: result.status === 0,
    stdout: result.stdout ?? '',
    stderr: result.stderr ?? '',
  };
}

// CNI required for NetworkPolicy enforcement. The live suite's
// minikube-live-network-policy tests assume Cilium (or another enforcing CNI)
// is installed; minikube's default bridge CNI silently ignores
// NetworkPolicies, which lets policy regressions ship without a test signal.
const REQUIRED_CNI = 'cilium';

function isEnforcingCniReady(): boolean {
  // Detect by checking for a Cilium DaemonSet in kube-system.
  const r = spawnSync(
    'kubectl',
    [
      'get',
      'daemonset',
      'cilium',
      '-n',
      'kube-system',
      '-o',
      'jsonpath={.status.numberReady}',
    ],
    { encoding: 'utf8' },
  );
  if (r.status !== 0) return false;
  const ready = parseInt(r.stdout.trim() || '0', 10);
  return ready > 0;
}

async function ensureMinikube(): Promise<void> {
  const which = run('which', ['minikube'], { allowFail: true });
  if (!which.ok) {
    throw new Error(
      'minikube is not installed and the live suite requires it for CNI control.',
    );
  }

  // Probe current minikube status. If running with the wrong CNI, recreate.
  const status = run('minikube', ['status', '--format={{.Host}}'], {
    allowFail: true,
  });
  const isRunning = status.ok && status.stdout.trim() === 'Running';

  if (isRunning && isEnforcingCniReady()) {
    console.log(`✅ minikube running with ${REQUIRED_CNI} CNI`);
    return;
  }

  if (isRunning) {
    console.log(
      `⚠️  minikube is running but ${REQUIRED_CNI} DaemonSet is not present — ` +
        'recreating cluster so NetworkPolicy enforcement is active.',
    );
    const del = run('minikube', ['delete'], {
      timeout: 120_000,
      allowFail: true,
    });
    if (!del.ok) {
      console.warn(
        '⚠️  minikube delete reported non-zero; continuing to start anyway.',
      );
    }
  }

  console.log(`🚀 Starting minikube with --cni=${REQUIRED_CNI}...`);
  // 8 GB / 4 CPU — the live-suite now installs ~6 capabilities at runtime
  // across the test files; under 4 GB/2 CPU the orchestrator's task-request
  // queue backs up and downstream test beforeAlls time out waiting for
  // Deployments.
  const start = run(
    'minikube',
    [
      'start',
      '--driver=docker',
      '--memory=8192',
      '--cpus=4',
      `--cni=${REQUIRED_CNI}`,
      '--wait=all',
    ],
    { timeout: 600_000 },
  );
  if (!start.ok) {
    throw new Error('minikube start failed');
  }
  run('kubectl', ['config', 'use-context', 'minikube']);
  run('kubectl', ['cluster-info']);

  console.log(`⏳ Waiting for ${REQUIRED_CNI} DaemonSet to be ready...`);
  const cniDeadline = Date.now() + 180_000;
  while (Date.now() < cniDeadline) {
    if (isEnforcingCniReady()) {
      console.log(`✅ ${REQUIRED_CNI} ready`);
      return;
    }
    await new Promise((r) => setTimeout(r, 3000));
  }
  throw new Error(`${REQUIRED_CNI} DaemonSet did not become Ready within 180s`);
}

function latestMtimeUnder(
  dir: string,
  exclude: Set<string> = new Set(['node_modules', '.git', '.claude', 'dist']),
): number {
  let latest = 0;
  const stack: string[] = [dir];
  while (stack.length) {
    const cur = stack.pop()!;
    let entries: string[];
    try {
      entries = readdirSync(cur);
    } catch {
      continue;
    }
    for (const name of entries) {
      if (exclude.has(name)) continue;
      const p = join(cur, name);
      let st;
      try {
        st = statSync(p);
      } catch {
        continue;
      }
      if (st.isDirectory()) stack.push(p);
      else if (st.mtimeMs > latest) latest = st.mtimeMs;
    }
  }
  return latest;
}

async function ensureImage(
  imageName: string,
  dockerfile: string,
  contextDir: string = '.',
  requiredFiles: string[] = [],
  sourceDirs: string[] = [],
): Promise<void> {
  console.log(`🐳 Checking for ${imageName} in minikube docker daemon...`);
  const check = spawnSync(
    'bash',
    [
      '-c',
      `eval $(minikube docker-env) && docker image inspect ${imageName} -f "{{.Id}}|{{.Created}}" 2>/dev/null`,
    ],
    { encoding: 'utf8' },
  );

  let needsBuild = !(check.status === 0 && check.stdout.trim());

  // Compare image creation time against the latest mtime under sourceDirs.
  // If any source file is newer, the image is stale and must be rebuilt.
  if (!needsBuild && sourceDirs.length > 0) {
    const created = check.stdout.split('|')[1]?.trim();
    const imageCreatedMs = created ? Date.parse(created) : NaN;
    if (Number.isFinite(imageCreatedMs)) {
      let latest = 0;
      for (const d of sourceDirs) {
        const m = latestMtimeUnder(d);
        if (m > latest) latest = m;
      }
      if (latest > imageCreatedMs) {
        console.log(
          `⚠️  ${imageName} is older than source files in ${sourceDirs.join(', ')} — rebuilding...`,
        );
        needsBuild = true;
      }
    }
  }

  // Even if the image exists, verify required files are present.
  // A stale image built from the wrong Dockerfile may be missing expected
  // artefacts (e.g. tool-server.js) causing tool pods to crash with
  // MODULE_NOT_FOUND at runtime.
  if (!needsBuild && requiredFiles.length > 0) {
    for (const f of requiredFiles) {
      const verify = spawnSync(
        'bash',
        [
          '-c',
          `eval $(minikube docker-env) && docker run --rm --entrypoint="" ${imageName} test -f ${f} 2>/dev/null`,
        ],
        { encoding: 'utf8' },
      );
      if (verify.status !== 0) {
        console.log(
          `⚠️  ${imageName} exists but is missing ${f} — rebuilding...`,
        );
        needsBuild = true;
        break;
      }
    }
  }

  if (!needsBuild) {
    console.log(`✅ ${imageName} already present\n`);
    return;
  }

  console.log(`🔨 Building ${imageName} inside minikube docker daemon...`);
  const build = spawnSync(
    'bash',
    [
      '-c',
      `eval $(minikube docker-env) && docker build -t ${imageName} -f ${dockerfile} ${contextDir}`,
    ],
    { encoding: 'utf8', stdio: 'inherit', timeout: 900_000 },
  );
  if (build.status !== 0) {
    throw new Error(`${imageName} build failed (exit ${build.status})`);
  }
  console.log(`✅ ${imageName} built\n`);
}

function waitForPod(labelSelector: string, timeoutMs: number): Promise<void> {
  return new Promise(async (resolve, reject) => {
    const deadline = Date.now() + timeoutMs;
    while (Date.now() < deadline) {
      const res = run(
        'kubectl',
        [
          'get',
          'pods',
          '-n',
          NAMESPACE,
          '-l',
          labelSelector,
          '-o',
          'jsonpath={.items[*].status.conditions[?(@.type=="Ready")].status}',
        ],
        { allowFail: true },
      );
      if (
        res.ok &&
        res.stdout
          .trim()
          .split(/\s+/)
          .every((s) => s === 'True')
      ) {
        return resolve();
      }
      await sleep(3000);
    }
    // Dump pod state for debugging
    const dump = run(
      'kubectl',
      ['get', 'pods', '-n', NAMESPACE, '-l', labelSelector, '-o', 'wide'],
      { allowFail: true },
    );
    reject(
      new Error(
        `pods matching ${labelSelector} not Ready within ${timeoutMs}ms\n${dump.stdout}\n${dump.stderr}`,
      ),
    );
  });
}

