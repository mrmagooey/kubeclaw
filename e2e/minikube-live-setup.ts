/**
 * Exported for tests that restart the channel pod — `kubectl port-forward`
 * dies when its backing pod is deleted, so the test re-runs setup.
 *
 * Kills the entire process group (bash wrapper + kubectl child) rather than
 * just the bash parent, then waits for the OS to release the listen port
 * before starting a new wrapper. Without this, the new kubectl fails with
 * "bind: address already in use" and the loop spins until TIME_WAIT expires.
 */
export async function restartChannelPortForward(): Promise<void> {
  if (portForwardProcess?.pid) {
    try {
      process.kill(-portForwardProcess.pid, 'SIGTERM');
    } catch {
      try {
        portForwardProcess.kill();
      } catch {
        /* ignore */
      }
    }
    portForwardProcess = null;
  }
  // Belt-and-braces: kill any stray kubectl holding the HTTP port.
  spawnSync('bash', [
    '-c',
    `pkill -f 'kubectl port-forward.*${KUBECLAW_LIVE_HTTP_LOCAL_PORT}:80' || true`,
  ]);
  // Give the OS TIME_WAIT to clear the listen socket (typically <1 s).
  await sleep(1000);
  await startPortForward();
}

async function teardownImpl() {
  // Kill the bash wrapper AND its child kubectl process. The wrapper restarts
  // kubectl in a loop, so killing only the wrapper leaves a stray kubectl.
  const killTree = (p: ChildProcess | null) => {
    if (!p?.pid) return;
    try {
      process.kill(-p.pid, 'SIGTERM');
    } catch {
      try {
        p.kill();
      } catch {
        /* ignore */
      }
    }
  };
  killTree(portForwardProcess);
  portForwardProcess = null;
  killTree(redisPortForwardProcess);
  redisPortForwardProcess = null;
  killTree(oauthWebchatPortForwardProcess);
  oauthWebchatPortForwardProcess = null;
  killTree(testOauthPortForwardProcess);
  testOauthPortForwardProcess = null;
  killTree(adminPortForwardProcess);
  adminPortForwardProcess = null;
  // Belt-and-braces: kill any lingering kubectl port-forward that targets our ports.
  spawnSync('bash', [
    '-c',
    `pkill -f 'kubectl port-forward.*${KUBECLAW_LIVE_HTTP_LOCAL_PORT}:80' || true`,
  ]);
  spawnSync('bash', [
    '-c',
    `pkill -f 'kubectl port-forward.*${KUBECLAW_LIVE_OAUTH_WEBCHAT_LOCAL_PORT}:80' || true`,
  ]);
  spawnSync('bash', [
    '-c',
    `pkill -f 'kubectl port-forward.*${KUBECLAW_LIVE_TEST_OAUTH_LOCAL_PORT}:8080' || true`,
  ]);
  spawnSync('bash', [
    '-c',
    `pkill -f 'kubectl port-forward.*${KUBECLAW_LIVE_REDIS_LOCAL_PORT}:6379' || true`,
  ]);
  spawnSync('bash', [
    '-c',
    `pkill -f 'kubectl port-forward.*${KUBECLAW_LIVE_ADMIN_LOCAL_PORT}:9090' || true`,
  ]);

  // Always uninstall — this is our own isolated namespace.
  run('helm', ['uninstall', RELEASE, '--namespace', NAMESPACE], {
    allowFail: true,
  });
  run(
    'kubectl',
    ['delete', 'namespace', NAMESPACE, '--ignore-not-found', '--timeout=60s'],
    { allowFail: true, timeout: 90_000 },
  );
}

